#pragma once

#include <cstdint>

constexpr int      PWM_RESOLUTION   = 11;
constexpr uint32_t PWM_MAX_VAL = (1<<PWM_RESOLUTION) - 1;

constexpr int SINE_LUT_IDX_RESOLUTION_bit =  6;
constexpr int SINE_LUT_IDX_RESOLUTION     = 64;
constexpr int THETA_INT_RESOLUTION_bit    = 32;

inline uint8_t theta_int_to_lut_idx(uint32_t theta) {
	return (uint8_t)(theta>>(THETA_INT_RESOLUTION_bit-SINE_LUT_IDX_RESOLUTION_bit));
}
const uint32_t SIN_LOOKUP[SINE_LUT_IDX_RESOLUTION] = {
	0x00000000, 0x000000C8, 0x0000018F, 0x00000252, 0x0000030F, 0x000003C4, 0x00000471, 0x00000512,
	0x000005A7, 0x0000062E, 0x000006A6, 0x0000070D, 0x00000763, 0x000007A6, 0x000007D7, 0x000007F5,
	0x000007FF, 0x000007F5, 0x000007D7, 0x000007A6, 0x00000763, 0x0000070D, 0x000006A6, 0x0000062E,
	0x000005A7, 0x00000512, 0x00000471, 0x000003C4, 0x0000030F, 0x00000252, 0x0000018F, 0x000000C8,
	0x00000000, 0x00C80000, 0x018F0000, 0x02520000, 0x030F0000, 0x03C40000, 0x04710000, 0x05120000,
	0x05A70000, 0x062E0000, 0x06A60000, 0x070D0000, 0x07630000, 0x07A60000, 0x07D70000, 0x07F50000,
	0x07FF0000, 0x07F50000, 0x07D70000, 0x07A60000, 0x07630000, 0x070D0000, 0x06A60000, 0x062E0000,
	0x05A70000, 0x05120000, 0x04710000, 0x03C40000, 0x030F0000, 0x02520000, 0x018F0000, 0x00C80000
};
inline uint32_t sin_lut(uint32_t x) {
	uint8_t lut_idx = theta_int_to_lut_idx(x);
	return SIN_LOOKUP[lut_idx];
}
